export function mergeLabInventory(existing) {
  const map = new Map(existing.map((x) => [x.id, { ...x }]));
  for (const incoming of labInventory) {
    const prior = map.get(incoming.id);
    map.set(incoming.id, {
      ...prior,
      ...incoming,
      aliases: [
        ...new Set([
          incoming.name,
          ...(prior?.aliases || []),
          incoming.name.replaceAll("Toluidine", "Toludine"),
          incoming.name
            .replace("Starch, potato", "Starch Potato")
            .replace("Starch, soluble", "Starch soluble"),
        ]),
      ],
    });
  }
  return [...map.values()];
}
