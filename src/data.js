export function pericyclicRule(electrons, mode) {
  const four = electrons === 4,
    thermal = mode === "thermal";
  return {
    motion: four === thermal ? "Conrotatory" : "Disrotatory",
    cyclo: four === thermal ? "Supra–antara" : "Supra–supra",
    alternative: four === thermal ? "Antara–supra" : "Antara–antara",
    phase: four ? "Opposite terminal phase" : "Same terminal phase",
    homo: four ? "ψ₂" : "ψ₃",
    lumo: four ? "ψ₃" : "ψ₄",
    active: four ? (thermal ? "ψ₂" : "ψ₃") : thermal ? "ψ₃" : "ψ₄",
  };
}
export function scheduleReview(previous, quality, now = Date.now()) {
  const old = previous || { interval: 0, repetitions: 0 };
  const interval =
    quality === "hard"
      ? 0
      : old.interval
        ? Math.min(Math.round(old.interval * 2.3), 90)
        : 1;
  return {
    interval,
    repetitions: quality === "hard" ? 0 : old.repetitions + 1,
    due: now + (quality === "hard" ? 10 * 60 * 1000 : interval * 86400000),
    last: quality,
  };
}
export function makeQuizCards(mode, level) {
  const items = (mode === "structure" ? compounds : reactions).filter(
    (x) =>
      matchesLevel(x, level) && (mode !== "structure" || Boolean(x.smiles)),
  );
  return items.map((x) => ({
    id: `${mode}:${x.id}`,
    item: x,
    answer:
      mode === "structure"
        ? x.name
        : mode === "reagent"
          ? x.conditions
          : x.product,
  }));
}
