export function buildWhatIfLab(base, atlas, reactions, reagents) {
  const groups = new Map();
  const byId = new Map(reagents.map((r) => [r.id, r]));
  let sequence = 0;
  const ensure = (smiles, name, formula = "") => {
    const key = canonical(smiles);
    if (!groups.has(key))
      groups.set(key, {
        id: "substrate-case-" + ++sequence,
        name,
        formula: formula || "Skeletal structure",
        smiles,
        level: "slot1",
        outcomes: [],
      });
    return groups.get(key);
  };
  const add = (group, outcome) => {
    const equivalent = group.outcomes.find(
      (o) =>
        canonical(o.smiles) === canonical(outcome.smiles) &&
        (o.reagentIds?.join(",") || o.label) ===
          (outcome.reagentIds?.join(",") || outcome.label),
    );
    if (equivalent) {
      equivalent.studyIds = [
        ...new Set([
          ...(equivalent.studyIds || []),
          ...(outcome.studyIds || []),
        ]),
      ];
      if (outcome.reactionId) equivalent.reactionId = outcome.reactionId;
      if (outcome.mechanismPathId)
        equivalent.mechanismPathId = outcome.mechanismPathId;
      return;
    }
    group.outcomes.push(outcome);
  };
  for (const b of base) {
    const g = {
      ...b,
      level: b.level || "slot2",
      outcomes: b.outcomes.map((o) => ({
        ...o,
        reagentIds: oldLinks[o.id] || [],
        source: "Curated substrate lab",
        mechanismPathId: {
          "luche-lab": "luche-enone",
          "grignard-lab": "grignard-ketone",
          "gilman-lab": "gilman-conjugate",
          "epoxide-lab": "dossier:hydrogen-peroxide:0",
          "wk-lab": "wk-hydrazone",
          "rh-lab": "rh-hydrogenation",
          "borohydride-lab": "nb-selective",
          "lah-lab": "lah-ester",
          "dibal-lab": "dibal-ester",
          "ketal-lab": "dossier:ethylene-glycol:0",
        }[o.id],
      })),
    };
    groups.set(canonical(b.smiles), g);
  }
  for (const [rid, c] of Object.entries(atlas)) {
    for (const p of c.pathways) {
      const g = ensure(p.reactant, p.starting);
      add(g, {
        id: p.id,
        label: byId.get(rid)?.name || rid,
        formula: p.conditions,
        level: c.level,
        product: p.product,
        smiles: p.productSmiles,
        kind: p.title,
        rule: p.why,
        trap: p.trap,
        conditions: p.conditions,
        reagentIds: [rid],
        source: "Reagent chapter",
        mechanismPathId: p.id,
      });
    }
  }
  for (const r of reactions.filter((r) => r.ncert)) {
    const parts = r.reactant.split(".");
    const smiles = parts[0],
      g = ensure(smiles, r.starting.split(/ \+ /)[0].replace(/^2 /, ""));
    add(g, {
      id: "lab-" + r.id,
      label: r.name,
      formula: r.conditions,
      level: r.level,
      product: r.product,
      smiles: r.productSmiles,
      kind: r.name,
      rule: r.easy,
      trap: r.trap,
      conditions: r.conditions,
      reagentIds: ncertLinks[r.id] || [],
      reactionId: r.id,
      source: "NCERT XI–XII",
    });
  }
  for (const [rid, cases] of Object.entries(caseData.cases)) {
    for (const [i, r] of cases.entries()) {
      if (!r[2] || !r[5] || !byId.has(rid)) continue;
      const g = ensure(r[2].split(".")[0], r[1]);
      const roleMap = {
        "n-butanol": [["swern"], "Swern oxidation"],
        "ethyl-acetate": [["lialh4"], "LiAlH₄"],
        thf: [["grignard"], "MeMgBr / THF"],
        dmf: [["grignard"], "PhMgBr; hydrolysis"],
        formaldehyde:
          i === 0
            ? [["grignard"], "RMgBr; work-up"]
            : [["sodium-hydroxide"], "Concentrated NaOH"],
        "ethyl-acetoacetate": [[], "Enolate alkylation; hydrolysis / heat"],
        pyridine: [["acetic-anhydride"], "Ac₂O / pyridine"],
        "ethylene-glycol":
          i === 0
            ? [["ethylene-glycol"], "Ethylene glycol / H⁺"]
            : [[], "H⁺ / H₂O"],
      };
      const [toolIds, caseLabel] = roleMap[rid] || [[rid], byId.get(rid).name];
      add(g, {
        id: "case-" + rid + "-" + i,
        label: caseLabel,
        formula: r[3],
        level: byId.get(rid).level,
        product: r[4],
        smiles: r[5],
        kind: r[0],
        rule: r[6],
        trap: byId.get(rid).trap,
        conditions: r[3],
        reagentIds: toolIds,
        studyIds: [rid],
        mechanismPathId: "dossier:" + rid + ":" + i,
        source: "Chemical dossier",
      });
    }
  }
  for (const [
    sid,
    name,
    smiles,
    formula,
    rid,
    label,
    product,
    ps,
    kind,
    rule,
    trap,
    conditions,
    level,
  ] of extra) {
    const g = ensure(smiles, name, formula);
    if (!g.formula || g.formula === "Skeletal structure") g.formula = formula;
    add(g, {
      id: "compare-" + sid + "-" + rid + "-" + g.outcomes.length,
      label,
      formula: label,
      level,
      product,
      smiles: ps,
      kind,
      rule,
      trap,
      conditions,
      reagentIds: [rid],
      source: "Curated comparison",
    });
  }
  return [...groups.values()]
    .map((g) => ({
      ...g,
      name:
        {
          "CC=O": "Ethanal",
          "CC=C": "Propene",
          "CC(=O)C": "Acetone",
          "COC(=O)C=C": "Methyl acrylate",
          "C=CC(=O)OC": "Methyl acrylate",
        }[canonical(g.smiles)] || g.name,
      level: g.outcomes.reduce(
        (best, o) => (o.level < best ? o.level : best),
        "slot3",
      ),
    }))
    .sort(
      (a, b) =>
        (a.id.startsWith("substrate-enone") ? -1000 : 0) -
          (b.id.startsWith("substrate-enone") ? -1000 : 0) ||
        b.outcomes.length - a.outcomes.length,
    );
}
export function relatedWhatIfCases(substrates, reagentId) {
  return substrates.flatMap((s) =>
    s.outcomes
      .filter(
        (o) =>
          o.reagentIds?.includes(reagentId) || o.studyIds?.includes(reagentId),
      )
      .map((o) => ({ substrate: s, outcome: o })),
  );
}
